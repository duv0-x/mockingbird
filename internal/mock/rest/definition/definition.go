// Package definition imports Swagger 2, OpenAPI 3, RAML 0.8/1.0 and WADL
// definitions into a REST project (SPEC.md §6.1).
//
// Owner: T2. Consumer: internal/api (T4) for /definition/file and /definition/link.
package definition

import (
	"context"
	"errors"
	"fmt"
	"io"
	"net/http"
	"net/url"
	"path"
	"strconv"
	"time"

	"github.com/duv0-x/mockingbird/internal/domain"
	"github.com/duv0-x/mockingbird/internal/storage"
)

// Source is either uploaded bytes (Filename+Data) or a URL to download.
type Source struct {
	Filename string
	Data     []byte
	URL      string
}

type Options struct {
	GenerateResponse bool
	HTTPClient       *http.Client
}

// ErrInvalidDefinition wraps every error caused by the definition itself
// (unparseable, missing mandatory parts, unknown type), as opposed to
// download or storage failures.
var ErrInvalidDefinition = errors.New("invalid definition")

const (
	autoGeneratedName  = "Auto-generated mocked response"
	defaultStatusCode  = 200
	downloadTimeout    = time.Minute
	maxDefinitionBytes = 64 << 20
)

// Import converts src and merges it into the project (ImportRestDefinitionService semantics).
func Import(ctx context.Context, repo storage.RestRepository, projectID string, defType domain.RestDefinitionType, src Source, opts Options) error {
	apps, err := Convert(ctx, defType, src, opts)
	if err != nil {
		return err
	}
	_, err = repo.Update(ctx, projectID, func(p *domain.RestProject) error {
		merge(p, apps)
		return nil
	})
	if err != nil {
		return fmt.Errorf("import %s definition into project %s: %w", defType, projectID, err)
	}
	return nil
}

// Convert parses src into applications with fresh ids, without touching any
// project. A Source with both a URL and data converts both, like the Java
// service handling a location and uploaded files in the same request.
func Convert(ctx context.Context, defType domain.RestDefinitionType, src Source, opts Options) ([]domain.RestApplication, error) {
	convert, err := converterFor(defType)
	if err != nil {
		return nil, err
	}
	var apps []domain.RestApplication
	if src.URL != "" {
		data, name, err := download(ctx, src.URL, opts.HTTPClient)
		if err != nil {
			return nil, err
		}
		converted, err := convert(data, name, opts.GenerateResponse)
		if err != nil {
			return nil, fmt.Errorf("%w: %s: %w", ErrInvalidDefinition, defType, err)
		}
		apps = append(apps, converted...)
	}
	if src.Data != nil || src.URL == "" {
		converted, err := convert(src.Data, src.Filename, opts.GenerateResponse)
		if err != nil {
			return nil, fmt.Errorf("%w: %s: %w", ErrInvalidDefinition, defType, err)
		}
		apps = append(apps, converted...)
	}
	for i := range apps {
		finish(&apps[i])
	}
	return apps, nil
}

type converter func(data []byte, filename string, generateResponse bool) ([]domain.RestApplication, error)

func converterFor(defType domain.RestDefinitionType) (converter, error) {
	switch defType {
	case domain.RestDefinitionOpenAPI:
		return convertOpenAPI, nil
	case domain.RestDefinitionSwagger:
		return convertSwagger, nil
	case domain.RestDefinitionRAML:
		return convertRAML, nil
	case domain.RestDefinitionWADL:
		return convertWADL, nil
	}
	return nil, fmt.Errorf("%w: unknown definition type %q", ErrInvalidDefinition, defType)
}

func download(ctx context.Context, location string, client *http.Client) ([]byte, string, error) {
	if client == nil {
		client = &http.Client{Timeout: downloadTimeout}
	}
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, location, nil)
	if err != nil {
		return nil, "", fmt.Errorf("%w: download %s: %w", ErrInvalidDefinition, location, err)
	}
	resp, err := client.Do(req)
	if err != nil {
		return nil, "", fmt.Errorf("download %s: %w", location, err)
	}
	defer resp.Body.Close()
	if resp.StatusCode < 200 || resp.StatusCode > 299 {
		return nil, "", fmt.Errorf("download %s: HTTP %d", location, resp.StatusCode)
	}
	data, err := io.ReadAll(io.LimitReader(resp.Body, maxDefinitionBytes))
	if err != nil {
		return nil, "", fmt.Errorf("download %s: %w", location, err)
	}
	name := ""
	if u, err := url.Parse(location); err == nil {
		name = path.Base(u.Path)
	}
	return data, name, nil
}

// finish assigns ids and parent ids and fills the defaults the Java builders
// leave to the repositories (empty lists, MOCKED/ENABLED statuses).
func finish(app *domain.RestApplication) {
	if app.ID == "" {
		app.ID = domain.NewID()
	}
	for i := range app.Resources {
		res := &app.Resources[i]
		if res.ID == "" {
			res.ID = domain.NewID()
		}
		res.ApplicationID = app.ID
		for j := range res.Methods {
			m := &res.Methods[j]
			if m.ID == "" {
				m.ID = domain.NewID()
			}
			m.ResourceID = res.ID
			for k := range m.MockResponses {
				r := &m.MockResponses[k]
				if r.ID == "" {
					r.ID = domain.NewID()
				}
				r.MethodID = m.ID
			}
		}
	}
	app.EnsureSlices()
}

// merge ports ImportRestDefinitionService: an application whose name equals
// (case-sensitively) an existing one is merged into it — resources matched by
// name, methods by name, new ones appended, existing ones left untouched —
// and other applications are added.
//
// CastleMock's merge is broken (the merged lists are dropped, see the
// "TODO: FIX" comments), so it never adds anything to an existing
// application; SPEC.md §6.1 asks for the intended behaviour.
func merge(p *domain.RestProject, apps []domain.RestApplication) {
	for _, app := range apps {
		existing := findApplication(p, app.Name)
		if existing == nil {
			app.ProjectID = p.ID
			p.Applications = append(p.Applications, app)
			continue
		}
		for _, res := range app.Resources {
			current := findResource(existing, res.Name)
			if current == nil {
				res.ApplicationID = existing.ID
				existing.Resources = append(existing.Resources, res)
				continue
			}
			for _, m := range res.Methods {
				if findMethod(current, m.Name) == nil {
					m.ResourceID = current.ID
					current.Methods = append(current.Methods, m)
				}
			}
		}
	}
}

func findApplication(p *domain.RestProject, name string) *domain.RestApplication {
	for i := range p.Applications {
		if p.Applications[i].Name == name {
			return &p.Applications[i]
		}
	}
	return nil
}

func findResource(a *domain.RestApplication, name string) *domain.RestResource {
	for i := range a.Resources {
		if a.Resources[i].Name == name {
			return &a.Resources[i]
		}
	}
	return nil
}

func findMethod(r *domain.RestResource, name string) *domain.RestMethod {
	for i := range r.Methods {
		if r.Methods[i].Name == name {
			return &r.Methods[i]
		}
	}
	return nil
}

// generatedResponse is AbstractRestDefinitionConverter.generateResponse.
func generatedResponse() domain.RestMockResponse {
	return domain.RestMockResponse{
		Name:             autoGeneratedName,
		HTTPStatusCode:   defaultStatusCode,
		Status:           domain.RestMockResponseEnabled,
		UsingExpressions: domain.Ptr(true),
	}
}

// statusCode mirrors extractHttpStatusCode: non-numeric codes ("default") are 200.
func statusCode(code string) int {
	n, err := strconv.Atoi(code)
	if err != nil {
		return defaultStatusCode
	}
	return n
}

func responseStatus(code int) domain.RestMockResponseStatus {
	if code == defaultStatusCode {
		return domain.RestMockResponseEnabled
	}
	return domain.RestMockResponseDisabled
}
